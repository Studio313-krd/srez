t=g.start('Выбрать день, магазин и срез')
t=g.p('Откройте <b>srez.studio313.ru</b> на телефоне или компьютере. Войдите с логином и паролем <b>своего магазина</b>, которые выдал руководитель. Вам нужен экран <b>«Отчёт за смену»</b>.',t)+3
