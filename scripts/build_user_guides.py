t=g.start('Исправить ошибку или ответить')
t=g.sub('Ошиблись в цифрах',t)
t=g.p('Снова откройте <b>тот же день и срез</b>. Исправьте число, заполните <b>«Причину исправления»</b> и нажмите <b>«Сохранить исправление»</b>. Дождитесь сообщения «Сохранено…».',t)+3
t=g.shot('seller-correction-v2',t,width=168)
t=g.p('Старая версия останется в «Истории отчёта». Не создавайте другой день или другой срез для исправления.',t,size=9.8,color=MUTED)+5
