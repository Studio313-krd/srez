t=g.start('Ввести показатели и сохранить')
t=g.p('<b>Укажите своё ФИО.</b> На подмене впишите его вручную. Затем введите <b>выручку, количество чеков и алкогольных единиц с начала дня</b>. При отсутствии продаж укажите нули.',t)+3
t=g.sub('Пример: что ввести в 17:00',t)
data=[['Показатель','На 13:00','Продали ещё','Ввести в 17:00'],['Выручка, ₽','5 000','7 000','12 000'],['Чеки','5','7','12'],['Алкогольные ед','8','10','18']]
